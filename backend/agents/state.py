"""AgentState — the shared state dictionary threaded through every LangGraph node.

Every node receives this state, mutates a subset of fields, and returns the
partial update.  LangGraph merges partials back into the shared state
automatically.
"""

from typing import TypedDict, Annotated, List
from langgraph.graph.message import add_messages


def _latest_str(a: str, b: str) -> str:
    """Reducer: always return the newer value. Used for current_phase."""
    return b


class AgentState(TypedDict, total=False):
    """Travel-planning state carried across the LangGraph pipeline.

    Fields are split into four logical groups for readability inside nodes.
    """

    # ── User input (raw) ────────────────────────────────────────
    user_input: dict
    #   { "origin": str, "destination": str, "start_date": str,
    #     "end_date": str, "budget": float, "preferences": [str],
    #     "pace": str }

    # ── Structured / intermediate ───────────────────────────────
    parsed_params: dict
    #   Normalised & enriched from user_input (e.g. parsed dates, defaults).
    weather_data: dict
    #   { "YYYY-MM-DD": { "condition": str, "high": float, "low": float } }
    poi_list: List[dict]
    #   Attraction candidates: [{ "name", "type", "rating", "cost", "location" }]
    food_list: List[dict]
    #   Restaurant candidates: [{ "name", "cuisine", "rating", "avg_cost", "location" }]

    # ── Agent outputs ───────────────────────────────────────────
    draft_itinerary: dict
    #   Intermediate plan generated by the LLM planner (before budget/weather).
    final_itinerary: dict
    #   The polished, validated TripPlan (serialisable to TripPlanResponse).
    budget_breakdown: dict
    #   { "total_budget", "total_spent", "over_budget", "by_day", "downgrade_notes" }
    downgrade_suggestions: list
    #   Structured downgrade adjustments generated when spending exceeds budget.
    weather_swaps: list
    #   Weather-driven itinerary changes emitted to the frontend for explanation.
    couple_notes: List[str]
    #   Per-activity couple messages, collected across nodes.
    messages: Annotated[list, add_messages]
    #   LLM conversation history managed by LangGraph's add_messages reducer.

    # ── Control ─────────────────────────────────────────────────
    current_phase: Annotated[str, _latest_str]
    #   Human-readable label for the active pipeline stage (used for SSE).
    #   Uses _latest_str reducer so parallel nodes don't collide.
    error: Annotated[str, _latest_str]
    #   Non-empty signals a recoverable or terminal problem. Uses _latest_str
    #   so parallel fetchers (weather/poi/food) can write without colliding.
    retry_count: int
    #   Budget-retry counter; capped at 2 to prevent infinite loops.
